//! Generation and lightweight inspection of RoboStack `pixi.toml` files.

use std::fmt::Write as _;

use toml::Value;

use crate::error::{Error, Result};
use crate::manifest::Manifest;
use crate::plan::shell_quote;
use crate::platform::Platform;

pub const GENERATED_MARKER: &str = "# generated by rospm from rospm.toml";

#[derive(Debug, Clone, PartialEq, Eq)]
pub struct PixiSummary {
    pub name: Option<String>,
    pub channels: Vec<String>,
    pub platforms: Vec<String>,
    pub ros_distro: Option<String>,
    pub dependencies: Vec<String>,
}

pub fn conda_platform(p: Platform) -> &'static str {
    match p {
        Platform::LinuxX86_64 => "linux-64",
        Platform::LinuxAarch64 => "linux-aarch64",
    }
}

pub fn generate(m: &Manifest) -> Result<String> {
    let distro = m.project.ros_distro.as_str();
    let mut out = String::new();
    writeln!(out, "{GENERATED_MARKER}").unwrap();
    writeln!(out, "[workspace]\nname = {}", quote(&m.project.name)).unwrap();
    writeln!(out, "channels = [\"robostack-{distro}\", \"conda-forge\"]").unwrap();
    let platforms = m
        .project
        .platforms
        .iter()
        .map(|p| format!("\"{}\"", conda_platform(*p)))
        .collect::<Vec<_>>()
        .join(", ");
    writeln!(out, "platforms = [{platforms}]\n").unwrap();

    writeln!(out, "[dependencies]").unwrap();
    let deps = [
        format!("ros-{distro}-ros-base"),
        "colcon-common-extensions".into(),
        "rosdep".into(),
        "vcstool".into(),
        "compilers".into(),
        "cmake".into(),
        "pkg-config".into(),
        "make".into(),
        "ninja".into(),
    ];
    for dep in deps {
        writeln!(out, "{} = \"*\"", quote(&dep)).unwrap();
    }
    writeln!(out, "\n[activation.env]").unwrap();
    for (key, value) in &m.env {
        writeln!(out, "{} = {}", quote(key), quote(value)).unwrap();
    }

    let order = m.build_order()?;
    for name in &order {
        let ws = &m.workspaces[name];
        let mut cmd = String::from("colcon build");
        for arg in &ws.colcon.build_args {
            cmd.push(' ');
            cmd.push_str(&shell_quote(arg));
        }
        writeln!(out, "\n[tasks.{}]", quote(&format!("build-{name}"))).unwrap();
        writeln!(out, "cmd = {}", quote(&cmd)).unwrap();
        writeln!(out, "cwd = {}", quote(&ws.path.to_string_lossy())).unwrap();
    }
    writeln!(out, "\n[tasks.build]").unwrap();
    let depends = order
        .iter()
        .map(|n| format!("\"build-{n}\""))
        .collect::<Vec<_>>()
        .join(", ");
    writeln!(out, "depends-on = [{depends}]").unwrap();
    Ok(out)
}

fn quote(s: &str) -> String {
    Value::String(s.to_owned()).to_string()
}

pub fn read_summary(text: &str) -> Result<PixiSummary> {
    let root: Value = text.parse().map_err(|source| Error::PixiParse {
        source: Box::new(source),
    })?;
    let table = root
        .get("workspace")
        .or_else(|| root.get("project"))
        .and_then(Value::as_table);
    let name = table
        .and_then(|t| t.get("name"))
        .and_then(Value::as_str)
        .map(str::to_owned);
    let channels: Vec<String> = table
        .and_then(|t| t.get("channels"))
        .and_then(Value::as_array)
        .map(|a| {
            a.iter()
                .filter_map(|v| {
                    v.as_str()
                        .map(str::to_owned)
                        .or_else(|| v.as_table()?.get("channel")?.as_str().map(str::to_owned))
                })
                .collect()
        })
        .unwrap_or_default();
    let platforms = table
        .and_then(|t| t.get("platforms"))
        .and_then(Value::as_array)
        .map(|a| {
            a.iter()
                .filter_map(Value::as_str)
                .map(str::to_owned)
                .collect()
        })
        .unwrap_or_default();
    let ros_distro = channels.iter().find_map(|c| {
        c.strip_prefix("robostack-")
            .filter(|d| !d.is_empty())
            .map(str::to_owned)
    });
    let dependencies = root
        .get("dependencies")
        .and_then(Value::as_table)
        .map(|t| t.keys().cloned().collect())
        .unwrap_or_default();
    Ok(PixiSummary {
        name,
        channels,
        platforms,
        ros_distro,
        dependencies,
    })
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::manifest::Manifest;

    fn manifest() -> Manifest {
        Manifest::parse(
            r#"
schema_version = 1
[project]
name = "demo"
ros_distro = "jazzy"
platforms = ["linux-x86_64", "linux-aarch64"]
[environment]
provider = "pixi"
[environment.pixi]
manifest = "pixi.toml"
[workspaces.base]
path = "base ws"
underlays = []
[workspaces.base.colcon]
build_args = ["--event-handlers", "console direct+"]
[workspaces.main]
path = "src"
underlays = ["base"]
[env]
Z_VAR = "two"
A_VAR = "one"
"#,
            std::path::Path::new("inline.toml"),
        )
        .unwrap()
    }

    #[test]
    fn generate_and_read() {
        let m = manifest();
        let a = generate(&m).unwrap();
        assert_eq!(a, generate(&m).unwrap());
        let _: Value = a.parse().unwrap();
        assert!(a.contains("robostack-jazzy"));
        assert!(a.contains("linux-aarch64"));
        assert!(a.contains("'console direct+'"));
        let s = read_summary(&a).unwrap();
        assert_eq!(s.name.as_deref(), Some("demo"));
        assert_eq!(s.ros_distro.as_deref(), Some("jazzy"));
        assert!(s.dependencies.contains(&"ros-jazzy-ros-base".to_string()));
    }

    #[test]
    fn tasks_follow_build_order_and_env_keeps_manifest_order() {
        let text = generate(&manifest()).unwrap();
        let v: Value = text.parse().unwrap();
        assert!(text.starts_with(GENERATED_MARKER));
        assert_eq!(
            v["workspace"]["platforms"],
            Value::Array(vec!["linux-64".into(), "linux-aarch64".into()])
        );
        assert_eq!(
            v["workspace"]["channels"],
            Value::Array(vec!["robostack-jazzy".into(), "conda-forge".into()])
        );
        let tasks = &v["tasks"];
        assert_eq!(
            tasks["build-base"]["cmd"].as_str(),
            Some("colcon build --event-handlers 'console direct+'")
        );
        assert_eq!(tasks["build-base"]["cwd"].as_str(), Some("base ws"));
        assert_eq!(tasks["build-main"]["cwd"].as_str(), Some("src"));
        assert_eq!(
            tasks["build"]["depends-on"],
            Value::Array(vec!["build-base".into(), "build-main".into()])
        );
        // `[activation.env]` in manifest order, not sorted.
        assert!(text.find("Z_VAR").unwrap() < text.find("A_VAR").unwrap());
        assert_eq!(v["activation"]["env"]["A_VAR"].as_str(), Some("one"));
    }

    #[test]
    fn manifest_without_env_still_parses() {
        let m = Manifest::parse(
            r#"
schema_version = 1
[project]
name = "q\"x"
ros_distro = "humble"
platforms = ["linux-x86_64"]
[environment]
provider = "pixi"
[environment.pixi]
[workspaces.main]
path = "ws"
"#,
            std::path::Path::new("inline.toml"),
        )
        .unwrap();
        let text = generate(&m).unwrap();
        let s = read_summary(&text).unwrap();
        assert_eq!(s.name.as_deref(), Some("q\"x"));
        assert_eq!(s.platforms, vec!["linux-64"]);
        assert_eq!(s.ros_distro.as_deref(), Some("humble"));
    }

    #[test]
    fn read_summary_rejects_invalid_toml() {
        assert!(matches!(
            read_summary("[workspace"),
            Err(Error::PixiParse { .. })
        ));
    }

    #[test]
    fn hand_written_project_and_tables() {
        let s = read_summary(
            r#"[project]
name = "x"
channels = [{ channel = "robostack-humble" }, "conda-forge"]
platforms = ["linux-64"]
[dependencies]
foo = "*"
"#,
        )
        .unwrap();
        assert_eq!(s.ros_distro.as_deref(), Some("humble"));
        assert_eq!(s.dependencies, vec!["foo"]);
    }
}
